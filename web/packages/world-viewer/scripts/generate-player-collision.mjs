// Reuse the same checked-in PrismarineJS data as Shapes1122.Data.cs. Attribution: third_party/minecraft-data/README.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../../../../', import.meta.url);
const read = file => JSON.parse(readFileSync(new URL(file, root), 'utf8'));
const source = read('third_party/minecraft-data/pc/1.12.2/blockCollisionShapes.json');
const blocks = read('third_party/minecraft-data/pc/1.12.2/blocks.json');
const states = Array(256).fill(1);
for (const block of blocks) states[block.id] = source.blocks[block.name] ?? 1;
const shapes = Array.from({length: Math.max(...Object.keys(source.shapes).map(Number)) + 1}, (_, i) => source.shapes[i] ?? []);
writeFileSync(new URL('../src/world/playerCollisionData.ts', import.meta.url),
  '// Generated by scripts/generate-player-collision.mjs from the same checked-in data as Shapes1122.Data.cs.\n' +
  '// PrismarineJS minecraft-data attribution/license: third_party/minecraft-data/README.\n' +
  'export type CollisionTuple = readonly [number, number, number, number, number, number];\n' +
  'export const COLLISION_STATES: readonly (number | readonly number[])[] = ' + JSON.stringify(states) + ';\n' +
  'export const COLLISION_SHAPES: readonly (readonly CollisionTuple[])[] = ' + JSON.stringify(shapes) + ';\n');
