// Generates src/lib/api/route-types.gen.ts from @mineclaw/contracts ROUTES.
//
// Why: ROUTES entries are built with get()/post() helpers that return the wide `RouteDef`, so the package's
// RouteResponse<K>/RouteQuery<K> helpers resolve to `unknown`. This script recovers the exact schema of every route by
// matching each schema object to the contracts export that holds it, and writes a typed map the client uses.
//
// Usage: node scripts/gen-route-types.mjs [--check]   (--check fails when the committed file is out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, '..', 'src', 'lib', 'api', 'route-types.gen.ts');

export async function generate() {
  const C = await import('@mineclaw/contracts');
  const names = new Map();
  for (const [name, value] of Object.entries(C)) {
    if (value && typeof value === 'object' && '_zod' in value && !names.has(value)) names.set(value, name);
  }
  const ref = (schema, route, part) => {
    if (!schema) return 'never';
    const name = names.get(schema);
    if (!name) throw new Error(`route ${route}: ${part} schema is not a named export of @mineclaw/contracts`);
    return name;
  };
  const used = new Set();
  const lines = [];
  for (const [id, r] of Object.entries(C.ROUTES)) {
    const parts = {
      params: ref(r.params, id, 'params'),
      query: ref(r.query, id, 'query'),
      body: ref(r.body, id, 'body'),
      response: ref(r.response, id, 'response'),
    };
    for (const v of Object.values(parts)) if (v !== 'never') used.add(v);
    const t = (v, io) => (v === 'never' ? 'never' : `z.${io}<typeof C.${v}>`);
    lines.push(
      `  '${id}': { params: ${t(parts.params, 'input')}; query: ${t(parts.query, 'input')}; body: ${t(parts.body, 'input')}; response: ${t(parts.response, 'output')} };`,
    );
  }
  return `// GENERATED by scripts/gen-route-types.mjs from @mineclaw/contracts ROUTES. Do not edit by hand.
// Run \`node scripts/gen-route-types.mjs\` after the contracts change (a test checks this file is current).
import type * as C from '@mineclaw/contracts';
import type { z } from 'zod';

/** Exact request/response types of every public route (input types for what the client sends, output for responses). */
export interface RouteTypes {
${lines.join('\n')}
}
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const text = await generate();
  if (process.argv.includes('--check')) {
    const current = readFileSync(out, 'utf8');
    if (current !== text) {
      console.error('route-types.gen.ts is out of date: run node scripts/gen-route-types.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(out, text);
    console.log(`wrote ${path.relative(process.cwd(), out)}`);
  }
}
