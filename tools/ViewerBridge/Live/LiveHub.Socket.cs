using System.Globalization;
using System.Net.WebSockets;
using System.Text;
using System.Text.Json;
using MineClaw.ViewerBridge.Security;

namespace MineClaw.ViewerBridge.Live;

public sealed partial class LiveHub
{
    /// <summary>Native socket fanout shares the SSE cursor, replay ring and backpressure policy; it starts no extra pollers.</summary>
    public async Task SocketAsync(HttpContext ctx)
    {
        if (!ctx.WebSockets.IsWebSocketRequest) { await ApiErrors.Write(ctx, 400, "bad_request", "WebSocket upgrade required"); return; }
        long? last = long.TryParse(ctx.Request.Headers["Last-Event-ID"].ToString(), NumberStyles.None, CultureInfo.InvariantCulture, out var value) ? value : null;
        using var socket = await ctx.WebSockets.AcceptWebSocketAsync();
        using var lifetime = CancellationTokenSource.CreateLinkedTokenSource(ctx.RequestAborted);
        var (client, replay, sent) = Subscribe(last);
        var write = SendFrames(socket, client, replay, sent, lifetime.Token);
        var read = ObserveClose(socket, lifetime.Token);
        try { await await Task.WhenAny(write, read); }
        catch (Exception ex) when (ex is WebSocketException or OperationCanceledException or IOException) { }
        finally
        {
            Unsubscribe(client);
            lifetime.Cancel();
            if (socket.State is WebSocketState.Open or WebSocketState.CloseReceived)
                try
                {
                    using var close = new CancellationTokenSource(250);
                    await socket.CloseOutputAsync(client.Lagging ? WebSocketCloseStatus.PolicyViolation : WebSocketCloseStatus.NormalClosure,
                        client.Lagging ? "Resync required" : "Connection closed", close.Token);
                }
                catch (Exception ex) when (ex is WebSocketException or OperationCanceledException) { }
            foreach (var task in new[] { write, read }) try { await task; } catch { }
        }
    }

    internal static byte[] SocketFrame(Frame frame)
    {
        // Frame.Text is generated by Format, with one JSON data line. Reuse its payload without a parse/clone/serialize pass.
        int start = frame.Text.IndexOf("\ndata: ", StringComparison.Ordinal) + 7;
        var json = frame.Text.AsSpan(start, frame.Text.Length - start - 2);
        return Encoding.UTF8.GetBytes(string.Concat("{\"event\":", JsonSerializer.Serialize(frame.Event), ",\"id\":",
            frame.Id.ToString(CultureInfo.InvariantCulture), ",\"data\":", json.ToString(), "}"));
    }

    private static async Task SendFrames(WebSocket socket, Client client, IReadOnlyList<Frame> replay, long sent, CancellationToken ct)
    {
        foreach (var frame in replay)
        {
            await socket.SendAsync(SocketFrame(frame).AsMemory(), WebSocketMessageType.Text, true, ct);
            sent = Math.Max(sent, frame.Id);
        }
        while (await client.Reader.WaitToReadAsync(ct))
        {
            if (client.Lagging) return; // reconnect from the cursor instead of playing stale movement after congestion
            while (client.Reader.TryRead(out var frame))
                if (frame.Id > sent)
                {
                    await socket.SendAsync(SocketFrame(frame).AsMemory(), WebSocketMessageType.Text, true, ct);
                    sent = frame.Id;
                }
        }
    }

    private static async Task ObserveClose(WebSocket socket, CancellationToken ct)
    {
        var buffer = new byte[1024];
        while (!ct.IsCancellationRequested)
        {
            var frame = await socket.ReceiveAsync(buffer.AsMemory(), ct);
            if (frame.MessageType == WebSocketMessageType.Close) return;
            // Viewer transport is read-only; inbound application messages are never interpreted as commands.
            if (!frame.EndOfMessage) return;
        }
    }
}
