namespace MineClaw.Complexity;

/// <summary>Finds the hand-written .cs files to measure: skips build output, generated code and (by default) tests.</summary>
internal sealed class SourceScanner(string root, bool includeTests)
{
    private static readonly HashSet<string> SkippedDirs = new(StringComparer.OrdinalIgnoreCase)
    {
        "bin", "obj", "node_modules", ".git", ".vs", ".idea", "third_party",
    };

    private static readonly string[] GeneratedSuffixes =
    [
        ".g.cs", ".g.i.cs", ".designer.cs", ".generated.cs", ".AssemblyInfo.cs", ".AssemblyAttributes.cs",
    ];

    /// <summary>The default roots: src/ and tools/, plus tests/ when tests are included.</summary>
    public IEnumerable<string> DefaultRoots()
    {
        string[] names = includeTests ? ["src", "tools", "tests"] : ["src", "tools"];
        return names.Select(n => Path.Combine(root, n)).Where(Directory.Exists);
    }

    /// <summary>Every measurable .cs file under <paramref name="paths"/> (files are taken as given), sorted.</summary>
    public IReadOnlyList<string> Files(IEnumerable<string> paths)
    {
        var files = new SortedSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var path in paths.Select(Path.GetFullPath))
        {
            if (File.Exists(path))
            {
                files.Add(path);
            }
            else if (Directory.Exists(path))
            {
                files.UnionWith(Walk(path));
            }
        }

        return [.. files];
    }

    private IEnumerable<string> Walk(string dir)
    {
        foreach (var file in Directory.EnumerateFiles(dir, "*.cs").Where(IsHandWritten))
        {
            yield return file;
        }

        foreach (var sub in Directory.EnumerateDirectories(dir).Where(KeepDirectory))
        {
            foreach (var file in Walk(sub))
            {
                yield return file;
            }
        }
    }

    private bool KeepDirectory(string dir)
    {
        var name = Path.GetFileName(dir);
        if (SkippedDirs.Contains(name))
        {
            return false;
        }

        return includeTests || !IsTestDirectory(name);
    }

    private static bool IsTestDirectory(string name) =>
        name.Equals("tests", StringComparison.OrdinalIgnoreCase)
        || name.EndsWith(".Tests", StringComparison.OrdinalIgnoreCase);

    private static bool IsHandWritten(string file)
    {
        if (GeneratedSuffixes.Any(s => file.EndsWith(s, StringComparison.OrdinalIgnoreCase)))
        {
            return false;
        }

        using var reader = new StreamReader(file);
        for (var i = 0; i < 5 && reader.ReadLine() is { } line; i++)
        {
            if (line.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase))
            {
                return false;
            }
        }

        return true;
    }

    /// <summary>The repo-relative path with forward slashes, e.g. <c>src/MineClaw.Hive/Story/StoryColony.cs</c>.</summary>
    public string Relative(string file) => Path.GetRelativePath(root, file).Replace('\\', '/');

    /// <summary>True when the repo-relative <paramref name="relative"/> is <paramref name="prefix"/> or lies under it.</summary>
    public static bool IsUnder(string relative, string prefix) =>
        relative.Equals(prefix, StringComparison.OrdinalIgnoreCase)
        || relative.StartsWith(prefix + "/", StringComparison.OrdinalIgnoreCase);

    /// <summary>The project a repo-relative file belongs to: <c>MineClaw.Hive</c>, <c>tools/SimServer</c>, <c>tests/MineClaw.Hive.Tests</c>.</summary>
    public static string ProjectOf(string relative)
    {
        var parts = relative.Split('/');
        if (parts.Length < 3)
        {
            return parts[0];
        }

        return parts[0] == "src" ? parts[1] : $"{parts[0]}/{parts[1]}";
    }

    /// <summary>The nearest directory at or above <paramref name="start"/> that holds MineClaw.sln.</summary>
    public static string FindRoot(string start)
    {
        for (var dir = new DirectoryInfo(start); dir is not null; dir = dir.Parent)
        {
            if (File.Exists(Path.Combine(dir.FullName, "MineClaw.sln")))
            {
                return dir.FullName;
            }
        }

        throw new ArgumentException($"no MineClaw.sln above {start}; pass --root");
    }
}
