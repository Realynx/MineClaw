    /// <summary>Pixel width of a string (no trailing gap).</summary>
    public static int Width(string text) => text.Length == 0 ? 0 : text.Length * Advance - 1;

    public static bool Has(char c) => Glyphs.ContainsKey(char.ToUpperInvariant(c));

    /// <summary>Draws text with its top-left at (x, y); unknown characters draw as '?'.</summary>
    public static void Draw(Canvas c, int x, int y, string text, uint colour)
    {
        foreach (char ch0 in text)
        {
            var g = Glyphs.GetValueOrDefault(char.ToUpperInvariant(ch0)) ?? Glyphs['?'];
            for (int row = 0; row < H; row++)
            {
                int bits = g[row];
                if (bits == 0) continue;
                for (int col = 0; col < W; col++)
                    if ((bits & (0x10 >> col)) != 0) c.Set(x + col, y + row, colour);
            }
            x += Advance;
        }
    }
}
